#!/usr/bin/env bash
set -euo pipefail

binary="${1:?Pass the gpx binary}"
app="${2:?Pass the output .app path}"
name="${3:?Pass the application name}"
identifier="${4:?Pass the bundle identifier}"
root="$(cd "$(dirname "$0")/.." && pwd)"
icon="${5:-$root/scripts/assets/AppIcon.icns}"
version="${6:-0.1.0}"
minimum_system_version="${7:-14.0}"
category="${8:-public.app-category.developer-tools}"

mkdir -p "$app/Contents/MacOS" "$app/Contents/Resources"
cp "$binary" "$app/Contents/MacOS/$name"
cp "$icon" "$app/Contents/Resources/AppIcon.icns"
plist="$app/Contents/Info.plist"
printf '%s\n' '<?xml version="1.0" encoding="UTF-8"?><!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd"><plist version="1.0"><dict/></plist>' > "$plist"
plutil -insert CFBundleExecutable -string "$name" "$plist"
plutil -insert CFBundleIdentifier -string "$identifier" "$plist"
plutil -insert CFBundleName -string "$name" "$plist"
plutil -insert CFBundleDisplayName -string "$name" "$plist"
plutil -insert CFBundleIconFile -string AppIcon.icns "$plist"
plutil -insert CFBundlePackageType -string APPL "$plist"
plutil -insert CFBundleShortVersionString -string "$version" "$plist"
plutil -insert CFBundleVersion -string "$version" "$plist"
plutil -insert LSMinimumSystemVersion -string "$minimum_system_version" "$plist"
plutil -insert NSHighResolutionCapable -bool YES "$plist"
plutil -insert LSApplicationCategoryType -string "$category" "$plist"
